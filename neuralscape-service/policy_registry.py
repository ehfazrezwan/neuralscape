class RegistryError(ValueError):
    """The registry and the operation inventory disagree or break a rule."""


def action_for(operation_id: str) -> str | None:
    """Return the mapped action, or ``None`` for an exempt operation."""

    return _entry(operation_id).action


def resolver_for(operation_id: str) -> tuple[str, str]:
    """Return ``(kind, target)`` describing how the resource is identified."""

    entry = _entry(operation_id)
    return entry.resolver_kind, entry.resolver_target


def _entry(operation_id: str) -> Entry:
    try:
        return REGISTRY[operation_id]
    except KeyError:
        raise RegistryError(f"unknown operation: {operation_id}") from None


def _is_console_route(operation_id: str) -> bool:
    """True only for a REST route whose path is ``/console`` or below it."""

    surface, _, rest = operation_id.partition(":")
    _, _, path = rest.partition(" ")
    segments = path.split("/")
    return (
        surface == "rest"
        and (path == "/console" or path.startswith("/console/"))
        and ".." not in segments
        and "%" not in path
    )


def _entry_problems(operation_id: str, entry: Entry) -> list[str]:
    problems: list[str] = []
    if entry.resolver_kind not in RESOLVER_KINDS:
        problems.append(f"{operation_id}: unknown resolver kind")
    if entry.status == "exempt":
        if entry.action is not None:
            problems.append(f"{operation_id}: exempt operation has an action")
        if not (entry.exempt_reason or "").startswith(EXEMPT_REASON_PREFIXES):
            problems.append(f"{operation_id}: exemption lacks an allowed reason")
        if entry.resolver_kind != "none" or entry.extra_actions:
            problems.append(f"{operation_id}: exempt operation names a resolver")
        if entry.privileged:
            problems.append(f"{operation_id}: exempt operation cannot be privileged")
        if (entry.exempt_reason or "").startswith(CONSOLE_SESSION_REASON) and not _is_console_route(operation_id):
            problems.append(f"{operation_id}: the console session exemption is only for /console routes")
        return problems
    if entry.status != "mapped":
        return [f"{operation_id}: unknown status"]
    if entry.action not in SUPPORTED_POLICY_ACTIONS:
        problems.append(f"{operation_id}: unsupported action")
    if entry.resolver_kind == "none" or not entry.resolver_target:
        problems.append(f"{operation_id}: mapped operation needs a resolver")
    if entry.exempt_reason:
        problems.append(f"{operation_id}: mapped operation has an exemption reason")
    if entry.privileged and (
        entry.action not in {"read", "update"} or entry.resolver_kind not in {"pool", "settings"}
    ):
        problems.append(f"{operation_id}: privileged operation must read or update a pool or settings")
    if entry.action in ADMIN_ACTIONS and entry.resolver_kind not in ADMIN_PRIMARY_RESOLVERS:
        problems.append(f"{operation_id}: admin action on a content resource")
    if entry.action in CONDITIONAL_ONLY_ACTIONS:
        problems.append(f"{operation_id}: {entry.action} is only a conditional extra")
    for extra, condition in entry.extra_actions:
        if extra not in SUPPORTED_POLICY_ACTIONS or not condition:
            problems.append(f"{operation_id}: invalid extra action")
        elif extra in ADMIN_ACTIONS:
            problems.append(f"{operation_id}: admin action implied by another action")
        elif extra in CONDITIONAL_ONLY_ACTIONS and entry.action not in CONTENT_WRITE_ACTIONS:
            problems.append(f"{operation_id}: {extra} on a non-write action")
    required = {
        "job_payload": WORKER_PAYLOAD_FIELDS,
        "system_worker": SYSTEM_WORKER_PAYLOAD_FIELDS,
    }.get(entry.resolver_kind, ())
    if entry.required_payload != required:
        problems.append(f"{operation_id}: wrong payload requirement for resolver")
    return problems


def validate_registry(
    operation_ids: Iterable[str],
    gates: Mapping[str, Iterable[str]] | None = None,
) -> None:
    """Fail unless the registry covers exactly ``operation_ids`` and is valid.

    ``gates`` maps operation ids to their observed in-handler gates (the
    inventory's ``authz_gate`` column).  When given, every operation observed
    behind an administrator gate must be privileged, so the separation is
    derived from source rather than from prose.
    """

    expected = set(operation_ids)
    problems = [f"unmapped operation: {i}" for i in sorted(expected - set(REGISTRY))]
    problems += [f"unknown registry entry: {i}" for i in sorted(set(REGISTRY) - expected)]
    for operation_id in sorted(expected & set(REGISTRY)):
        problems += _entry_problems(operation_id, REGISTRY[operation_id])
    marked = {i for i, entry in REGISTRY.items() if entry.privileged}
    if marked != PRIVILEGED_OPERATIONS & set(REGISTRY) and expected >= PRIVILEGED_OPERATIONS:
        problems.append("privileged set differs from the pinned set")
    for operation_id, observed in (gates or {}).items():
        entry = REGISTRY.get(operation_id)
        if entry is not None and ADMIN_GATES & set(observed) and not entry.privileged:
            problems.append(f"{operation_id}: administrator-gated but not privileged")
    for operation_id in sorted(PENDING_ADMIN_DECISION & set(REGISTRY)):
        if "decision pending:" not in REGISTRY[operation_id].note:
            problems.append(f"{operation_id}: pending decision is not recorded in the note")
    if problems:
        raise RegistryError("; ".join(problems))


