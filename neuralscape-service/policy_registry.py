"""Canonical authorization action registry for every inventoried operation.

Each operation id (see ``tests/fixtures/policy_operation_inventory.json``) is
mapped to exactly one of the policy actions, or carries an explicit exemption
reason, plus a target-resolver spec saying which request field identifies the
resource.  This is DATA: nothing here is wired into middleware, handlers or
workers, and nothing here grants access.  The tenant always comes from the
verified credential, never from a request field.

Separation rules (enforced by ``validate_registry``):

* ``manage_membership``, ``manage_credentials`` and ``publish_standard`` are
  never implied by a content action.  ``manage_*`` appear only as the primary
  action of credential/connector/issuance operations; ``publish_standard`` and
  ``share`` appear only as conditional extra checks on content writes.
* Exemptions are limited to public liveness, static metadata, OAuth protocol
  endpoints and the optional console's own session pages, and each carries a
  reason.  A console page holds no data of its own: each action calls a public
  API route with the signed-in credential, and that route is authorized.
* Background work is ``background_derive``/``background_replay`` and names the
  payload fields a worker must carry for the policy-epoch fence.
"""

