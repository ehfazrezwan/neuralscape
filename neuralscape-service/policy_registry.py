class Entry(NamedTuple):
    action: str | None
    status: str  # "mapped" | "exempt"
    resolver_kind: str
    resolver_target: str
    extra_actions: tuple[tuple[str, str], ...]
    exempt_reason: str | None
    required_payload: tuple[str, ...]
    privileged: bool
    note: str


def _e(
    action: str | None,
    status: str,
    resolver_kind: str,
    resolver_target: str,
    *,
    extra_actions: tuple[tuple[str, str], ...] = (),
    exempt_reason: str | None = None,
    required_payload: tuple[str, ...] = (),
    privileged: bool = False,
    note: str = "",
) -> Entry:
    return Entry(
        action,
        status,
        resolver_kind,
        resolver_target,
        extra_actions,
        exempt_reason,
        required_payload,
        privileged,
        note,
    )


