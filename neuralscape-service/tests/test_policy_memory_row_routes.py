T = "tenant-a"
SECRET = "row-routes-secret"
ORIG = "original text"


def payload(owner, visibility, **extra):
    meta = {"owner_user_id": owner, **({} if visibility is None else {"visibility": visibility}), **extra}
    return {"id": "x", "user_id": owner, "memory": ORIG, "metadata": meta}


ROWS = {
    "m-shared-alice": payload("alice", "shared"),
    "m-private-alice": payload("alice", "private"),
    "m-null-vis-alice": payload("alice", None),                       # legacy null visibility = private
    "m-double-wrapped": {"id": "x", "user_id": "alice", "memory": ORIG,
                         "metadata": {"metadata": {"owner_user_id": "alice", "visibility": "shared"}}},
    "m-standard": payload("carol", "standard"),
    "m-quarantined": payload("frank", "shared"),                      # owner is not a unique, bound user
    "m-unowned": {"id": "x", "memory": ORIG, "metadata": {"visibility": "shared"}},
}


