def denied(response) -> bool:
    body = response.json()
    detail = body.get("detail") if isinstance(body, dict) else None
    return response.status_code == 404 and isinstance(detail, dict) and detail["error"]["code"] == "not_found"


def patch(w, user, row, body):
    before = w.service.patch_memory.call_count
    response = w.call(user, "PATCH", f"/v1/memories/{row}", json=body)
    return response, w.service.patch_memory.call_count - before


def delete(w, user, row):
    before = w.service.delete_memory.call_count
    response = w.call(user, "DELETE", f"/v1/memories/{row}")
    return response, w.service.delete_memory.call_count - before


def test_the_author_edits_and_deletes_a_shared_row_and_others_edit_only_metadata(world) -> None:
    w = world
    for body in ({"content": "new"}, {"tags": ["t"]}, {"visibility": "private"}):
        response, ran = patch(w, "alice", "m-shared-alice", body)
        assert response.status_code == 200 and ran == 1, body
    for body in ({"content": "new"}, {"visibility": "private"}, {"tags": ["t"], "content": "new"}):
        response, ran = patch(w, "bob", "m-shared-alice", body)
        assert denied(response) and ran == 0, body
    for body in ({"tags": ["t"], "category": "decision"}, {"content": ORIG, "tags": ["t"]},
                 {"tags": ["t"], "owner_user_id": "bob", "scope": "project"}):
        response, ran = patch(w, "bob", "m-shared-alice", body)
        assert response.status_code == 200 and ran == 1, body
    response, ran = patch(w, "bob", "m-shared-alice", {"owner_user_id": "bob"})
    assert denied(response) and ran == 0                               # the service applies nothing
    assert denied(delete(w, "bob", "m-shared-alice")[0]) and w.service.delete_memory.call_count == 0
    response, ran = delete(w, "alice", "m-shared-alice")
    assert response.status_code == 200 and ran == 1


def test_private_rows_belong_to_their_owner_whatever_the_visibility_spelling(world) -> None:
    w = world
    for row in ("m-private-alice", "m-null-vis-alice"):
        assert patch(w, "alice", row, {"content": "x"})[0].status_code == 200
        assert delete(w, "alice", row)[0].status_code == 200
        assert denied(patch(w, "bob", row, {"tags": ["t"]})[0])
        assert denied(delete(w, "bob", row)[0])
        assert denied(w.call("bob", "GET", f"/v1/memories/{row}"))
        assert not denied(w.call("alice", "GET", f"/v1/memories/{row}"))              # reached its handler
    # mem0's double-wrapped metadata is read the same way as the delete path does
    assert patch(w, "alice", "m-double-wrapped", {"content": "x"})[0].status_code == 200
    assert denied(patch(w, "bob", "m-double-wrapped", {"content": "x"})[0])


def test_a_dictator_keeps_cross_user_edit_and_delete_but_not_private_reads(world) -> None:
    w = world
    for row in ("m-shared-alice", "m-private-alice"):
        assert patch(w, "carol", row, {"content": "x"})[0].status_code == 200
        assert delete(w, "carol", row)[0].status_code == 200
    assert denied(w.call("carol", "GET", "/v1/memories/m-private-alice"))      # reads are not edit powers
    # standard rows need publish_standard plus update/delete on the standard pool
    assert patch(w, "carol", "m-standard", {"content": "x"})[0].status_code == 200
    assert denied(patch(w, "alice", "m-standard", {"content": "x"})[0])
    assert denied(delete(w, "bob", "m-standard")[0])


def test_unknown_unowned_and_quarantined_rows_are_denied_identically(world) -> None:
    w = world
    forbidden = patch(w, "bob", "m-private-alice", {"tags": ["t"]})[0].json()
    for row in ("m-missing", "m-unowned", "m-quarantined"):
        for user in ("alice", "bob", "carol"):
            response, ran = patch(w, user, row, {"tags": ["t"]})
            assert denied(response) and response.json() == forbidden and ran == 0, (row, user)
            assert denied(delete(w, user, row)[0])


def test_the_shared_key_acts_for_the_user_it_asserts(world) -> None:
    w = world
    key = lambda body: w.call(None, "PATCH", "/v1/memories/m-shared-alice", json=body)  # noqa: E731
    assert key({"content": "x", "user_id": "alice"}).status_code == 200            # as the author
    assert denied(key({"content": "x", "user_id": "bob"}))                          # not as someone else
    assert key({"tags": ["t"], "user_id": "bob"}).status_code == 200                # metadata as any member
    assert denied(key({"content": "x", "user_id": "frank"}))                        # a quarantined user
    assert denied(key({"content": "x", "user_id": "carol"}))                        # never a dictator's powers
    private = lambda user: w.call(None, "PATCH", "/v1/memories/m-private-alice", json={"tags": ["t"], "user_id": user})  # noqa: E731
    assert private("alice").status_code == 200
    assert denied(private("bob"))
    assert denied(w.call(None, "PATCH", "/v1/memories/m-standard", json={"content": "x", "user_id": "carol"}))


def test_observe_mode_never_changes_or_breaks_row_operations(world, monkeypatch) -> None:
    w = world
    monkeypatch.setattr(settings, "ns_policy_mode", "observe")
    for user, row, body in (("bob", "m-shared-alice", {"content": "x"}), ("bob", "m-private-alice", {"tags": ["t"]}),
                            ("alice", "m-missing", {"tags": ["t"]}), ("bob", "m-quarantined", {"tags": ["t"]})):
        response, ran = patch(w, user, row, body)
        assert response.status_code == 200 and ran == 1


def test_the_row_is_read_fresh_for_every_request(world) -> None:
    w = world
    before = len(w.fetches)
    patch(w, "alice", "m-shared-alice", {"tags": ["t"]})
    patch(w, "alice", "m-shared-alice", {"tags": ["t"]})
    assert len(w.fetches) - before == 2                                  # no caching of owner or visibility
    ROWS["m-flip"] = payload("alice", "shared")
    try:
        assert patch(w, "bob", "m-flip", {"tags": ["t"]})[0].status_code == 200
        ROWS["m-flip"] = payload("alice", "private")                      # made private after the fact
        assert denied(patch(w, "bob", "m-flip", {"tags": ["t"]})[0])
    finally:
        ROWS.pop("m-flip", None)
